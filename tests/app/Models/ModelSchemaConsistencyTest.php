<?php

declare(strict_types=1);

namespace Tests\App\Models;

use CodeIgniter\Test\DatabaseTestTrait;
use Tests\Support\BaseTestCase;

/**
 * Every model's declared shape must match the table its migrations create.
 *
 * This exists because a model can be wrong in ways nothing else notices. The
 * transaction model declared CI4 timestamps for a table with no
 * `created_at`/`updated_at` and an auto-increment key for a `VARCHAR` primary
 * key; both made every insert and update throw, and both were invisible until
 * something happened to write a row. A model that names a column its table does
 * not have is not a style problem — it is a latent 500.
 *
 * The checks are deliberately about *declarations*, read by reflection so no
 * model is instantiated and nothing is written:
 *
 *  - the table exists at all
 *  - `$primaryKey` is a real column
 *  - `$allowedFields` are real columns (an allowed field that is not a column is
 *    silently dropped by field protection, so the data never lands)
 *  - `$useTimestamps` implies `$createdField`/`$updatedField` exist
 *  - `$useSoftDeletes` implies `$deletedField` exists
 *  - `$useAutoIncrement` implies an integer primary key, since a VARCHAR key
 *    cannot be generated by the database
 *  - `$validationRules` and `$casts` only name real columns
 *
 * The schema compared against is the one this suite runs on, built by the
 * migrations themselves — so "matches its migration" is literally what is
 * checked.
 *
 * @internal
 */
final class ModelSchemaConsistencyTest extends BaseTestCase
{
    use DatabaseTestTrait;

    protected $namespace = 'App';
    protected $refresh   = false;

    /**
     * Calls whose first argument names a *table*.
     *
     * @var list<string>
     */
    private const TABLE_CALLS = ['table', 'from', 'tableexists'];

    /**
     * Calls whose first argument names a *column*. `join` is absent on purpose:
     * its first argument is a table and its second is a condition expression, so
     * neither is a bare column name.
     *
     * @var list<string>
     */
    private const COLUMN_CALLS = [
        'where', 'orwhere', 'wherein', 'wherenotin', 'wherenot', 'like', 'notlike',
        'orderby', 'groupby', 'having', 'set', 'select',
    ];

    /**
     * Calls whose first argument is an *array* of values to write, keyed by
     * column. `set` is in both lists on purpose: `set('col', $v)` and
     * `set(['col' => $v])` are the same write in two shapes.
     *
     * @var list<string>
     */
    private const ARRAY_WRITE_CALLS = ['insert', 'update', 'insertbatch', 'updatebatch', 'save', 'replace', 'upsert', 'set'];

    /**
     * Write calls that build a whole row, and so must carry every required
     * column. `update` and `set` are absent: writing one column is the point.
     *
     * @var list<string>
     */
    private const INSERT_CALLS = ['insert', 'insertbatch'];

    /**
     * What every audit entry must record, whatever subsystem writes it.
     *
     * The first four are NOT NULL, both in the migration and on the appliances
     * already running (see the audit test above). `username` and `action` are the
     * two columns the Diagnostics audit trail renders as *Administrator* and
     * *Action Code*, so an entry without them is a blank row in the one place an
     * operator reads it.
     *
     * @var list<string>
     */
    private const AUDIT_CORE_COLUMNS = [
        'admin_user', 'client_ip', 'action_type', 'target_resource',
        'username', 'action',
    ];

    /**
     * Calls whose literal argument asks *whether* a schema object exists.
     *
     * These are questions, not assertions, and "no" is a legitimate answer:
     * `in_array('position', $fields)` / `fieldExists('last_status', ...)` in the
     * guarded paths mean exactly "use it if the schema has it". Reporting them as
     * typos would make the sweep fire on the code that already anticipates a
     * missing column. Anywhere else, a name no table has is a real defect.
     *
     * @var list<string>
     */
    private const PRESENCE_PROBES = ['fieldexists', 'tableexists', 'in_array', 'array_key_exists'];

    /**
     * Receivers whose `->set('name', ...)` writes a *key*, not a column: CI4's
     * `Session::set()` and `View::set()`. Judging those would report every
     * session key as a missing column, which is most of them.
     *
     * @var list<string>
     */
    private const NON_COLUMN_SETTERS = ['session', 'view'];

    /**
     * Tables that code names deliberately, whose migration is still to come.
     *
     * A table may only be tolerated here *and* only where the same file guards it
     * with `tableExists()` — so this is a list of known absences, never a blanket
     * exemption. The connector tables land in Phase 2 (`ConnectorSync.php:22`,
     * `BackupEngine.php:359`). `testDeclaredFutureTablesAreStillFuture()` fails
     * once a table arrives, so an entry cannot outlive its reason.
     *
     * @var array<string, string>
     */
    private const DECLARED_NOT_YET_MIGRATED = [
        'connector_instances' => 'Phase 2 connectors — ConnectorSync.php:22',
        'connector_targets'   => 'Phase 2 connectors — ConnectorSync.php:22',
        'connector_secrets'   => 'Phase 2 connectors — ConnectorSync.php:22',
    ];

    /** Only bare names are judged; anything qualified, aliased or computed is left alone. */
    private const BARE_IDENTIFIER = '/^[a-z][a-z0-9_]*$/i';

    /** @var array<string, list<string>>|null */
    private ?array $schema = null;

    public function testEveryModelMatchesItsTable(): void
    {
        $findings = [];

        foreach ($this->modelClasses() as $class) {
            foreach ($this->inspect($class) as $finding) {
                $findings[] = $finding;
            }
        }

        $this->assertSame([], $findings, $this->report($findings));
    }

    /**
     * The guard has to be looking at real models *and* a real schema, or it
     * proves nothing — and it must not report a schema it failed to read as
     * "every table is missing", which is the failure mode that looks like a
     * hundred findings.
     */
    public function testTheAuditCanSeeBothTheModelsAndTheSchema(): void
    {
        $classes = $this->modelClasses();

        $this->assertGreaterThanOrEqual(25, count($classes), 'the model directory scan must find the application models');
        $this->assertContains(\App\Models\ConfigTransactionModel::class, $classes);
        $this->assertContains(\App\Models\DhcpServerSettingsModel::class, $classes);

        // The reference scan must keep covering code that is not a model — a
        // sweep that quietly narrowed to Models\\ would leave every controller
        // and library unchecked while still passing.
        $files = array_map(static fn (string $path): string => str_replace('\\', '/', $path), $this->schemaReferencingFiles());

        foreach (['/app/Controllers/', '/app/Libraries/', '/app/Commands/', '/app/Filters/', '/app/Views/'] as $directory) {
            $covered = array_filter($files, static fn (string $path): bool => str_contains($path, $directory));

            $this->assertNotSame([], $covered, "the reference scan must cover {$directory}");
        }

        $schema = $this->schema();

        $this->assertGreaterThanOrEqual(
            25,
            count($schema),
            'the migrated schema must be readable; a model naming a table that is not in this map is reported as missing'
        );
        $this->assertArrayHasKey('config_transactions', $schema, 'tables must be keyed by their unprefixed name, which is what models declare');
        $this->assertContains('confirmed_at', $schema['config_transactions']);
        $this->assertContains('id', $schema['config_transactions']);
    }

    /**
     * Every table named in application code outside the migrations must exist.
     *
     * A renamed or mistyped table does not fail loudly: `table('x')->get()` on a
     * missing table throws, but `countAllResults()` in a try/catch, or a curated
     * list like the backup engine's, silently reports nothing — which is exactly
     * how a subsystem can look empty forever.
     */
    public function testEveryTableNamedInCodeExists(): void
    {
        $findings = [];

        foreach ($this->schemaReferencingFiles() as $path) {
            $calls = $this->literalCallArgs($path);

            // A table this file asks about with `tableExists()`. Only a name in
            // DECLARED_NOT_YET_MIGRATED may actually be absent; a stale name that
            // happens to sit inside such a guard (`nat_rules` did) is still a
            // defect, which is why the guard alone is not enough.
            $guarded = $this->presenceProbes($calls, ['tableexists']);

            foreach ($calls as [$call, $literal, $line]) {
                if (! in_array($call, self::TABLE_CALLS, true)) {
                    continue;
                }

                // `table('users u')` and `table('users as u')` name a table with
                // an alias; only the name is checked.
                $name = preg_split('/\s+/', trim($literal))[0] ?? '';

                if (preg_match(self::BARE_IDENTIFIER, $name) !== 1 || array_key_exists($name, $this->schema())) {
                    continue;
                }

                if (array_key_exists($name, self::DECLARED_NOT_YET_MIGRATED) && isset($guarded[$name])) {
                    continue;
                }

                $findings[] = $this->at($path, $line) . "->{$call}('{$name}') names a table that does not exist";
            }
        }

        $this->assertSame([], $findings, $this->report($findings));
    }

    /**
     * An exemption that outlives its cause is how a guard rots. When Phase 2
     * migrates the connector tables this fails, and the entry has to go.
     */
    public function testDeclaredFutureTablesAreStillFuture(): void
    {
        $schema = $this->schema();
        $source = $this->applicationSource();

        foreach (self::DECLARED_NOT_YET_MIGRATED as $table => $reason) {
            $this->assertArrayNotHasKey(
                $table,
                $schema,
                "'{$table}' ({$reason}) now exists in the migrated schema; remove it from DECLARED_NOT_YET_MIGRATED"
            );

            $this->assertStringContainsString(
                $table,
                $source,
                "'{$table}' is exempted as {$reason} but is no longer named in code; remove it from DECLARED_NOT_YET_MIGRATED"
            );
        }
    }

    /**
     * Every scanned file, concatenated: the exemption above is about a name being
     * used, which the path list cannot answer.
     */
    private function applicationSource(): string
    {
        $source = '';

        foreach ($this->schemaReferencingFiles() as $path) {
            $source .= (string) file_get_contents($path);
        }

        return $source;
    }

    /**
     * Column names used as literals must exist in the schema *somewhere*.
     *
     * This catches misspelt columns (`confirmmed_at`), which a query silently
     * treats as a non-matching predicate. It deliberately does not judge whether
     * a column exists on the table the query is aimed at — that needs type
     * information the codebase does not carry, and is what the model audit above
     * covers for the places where a table is declared in one place.
     */
    public function testEveryColumnNamedInCodeExistsSomewhere(): void
    {
        $known    = $this->allColumns();
        $findings = [];

        foreach ($this->schemaReferencingFiles() as $path) {
            $calls = $this->literalCallArgs($path);

            // Columns this file asks about rather than assumes, and row keys of
            // the session and the view. Both are excluded, for the reasons on
            // the constants above.
            $probed = $this->presenceProbes($calls);

            foreach ($calls as [$call, $literal, $line, $chain]) {
                if (! in_array($call, self::COLUMN_CALLS, true)) {
                    continue;
                }

                if (isset($probed[$literal]) || $this->writesARowKey($chain)) {
                    continue;
                }

                if (preg_match(self::BARE_IDENTIFIER, $literal) === 1 && ! isset($known[strtolower($literal)])) {
                    $findings[] = $this->at($path, $line) . "->{$call}('{$literal}') names a column no table has";
                }
            }
        }

        $this->assertSame([], $findings, $this->report($findings));
    }

    /**
     * The keys of an array handed to a write are column names too — and this is
     * where the codebase writes: `->insert([...])` and `->update([...])` appear
     * hundreds of times, far more than any query-builder predicate.
     *
     * A key that is not a column fails in the two ways this whole audit exists
     * for: on a model with field protection it is dropped without a word, and on
     * the query builder it throws. Either way the column simply never receives
     * the value, and the write looks like it succeeded.
     */
    public function testEveryColumnKeyedInAWriteArrayExists(): void
    {
        $known    = $this->allColumns();
        $findings = [];

        foreach ($this->schemaReferencingFiles() as $path) {
            $probed = $this->presenceProbes($this->literalCallArgs($path));

            foreach ($this->literalArrayWrites($path) as $write) {
                if (! in_array($write['call'], self::ARRAY_WRITE_CALLS, true) || $this->writesARowKey($write['chain'])) {
                    continue;
                }

                foreach ($write['keys'] as [$key, $line]) {
                    if (isset($probed[$key]) || isset($known[strtolower($key)])) {
                        continue;
                    }

                    if (preg_match(self::BARE_IDENTIFIER, $key) === 1) {
                        $findings[] = $this->at($path, $line) . "->{$write['call']}(['{$key}' => ...]) writes a column no table has";
                    }
                }
            }
        }

        $this->assertSame([], $findings, $this->report($findings));
    }

    /**
     * An insert has to supply every column its table requires — a literal array
     * that omits one is a guaranteed runtime failure, and whichever try/catch
     * surrounds it decides whether anyone hears about it.
     *
     * Judged against the migrated schema rather than a model declaration, so a
     * table written straight through the query builder is covered too.
     */
    public function testEveryInsertSuppliesTheColumnsItsTableRequires(): void
    {
        $findings = [];
        $judged   = 0;

        foreach ($this->schemaReferencingFiles() as $path) {
            foreach ($this->literalArrayWrites($path) as $write) {
                // `update([...])` sets a subset by design; only a write that has
                // to build a whole row is judged.
                if (! in_array($write['call'], self::INSERT_CALLS, true) || $write['table'] === null) {
                    continue;
                }

                $judged++;

                $required = $this->requiredColumns($write['table']);
                if ($required === null) {
                    continue;
                }

                $supplied = array_map(strtolower(...), array_column($write['keys'], 0));

                foreach ($required as $column) {
                    if (! in_array(strtolower($column), $supplied, true)) {
                        $findings[] = $this->at($path, $write['line'])
                            . "->{$write['call']}([...]) into '{$write['table']}' omits '{$column}', which the column requires";
                    }
                }
            }
        }

        // A scan that judged nothing would pass while proving nothing.
        $this->assertGreaterThanOrEqual(20, $judged, 'the scan must reach the literal inserts');
        $this->assertSame([], $findings, $this->report($findings));
    }

    /**
     * Every writer of an audit entry records the same core columns.
     *
     * `admin_user`, `client_ip`, `action_type` and `target_resource` are NOT NULL,
     * and an appliance whose database was created by an earlier revision of the
     * migration enforced that while the file itself said otherwise — the file was
     * relaxed to nullable after the fact. A writer that satisfied only the file
     * therefore failed on every real appliance, inside a bare
     * `catch (\Throwable)` that discarded the reason: the audit trail for six
     * subsystems was empty for exactly that reason. The declaration now matches
     * the appliances, and this is what keeps a writer from drifting off it.
     */
    public function testEveryAuditWriteSuppliesTheSameCoreColumns(): void
    {
        $findings = [];
        $writers  = 0;

        foreach ($this->schemaReferencingFiles() as $path) {
            foreach ($this->literalArrayWrites($path) as $write) {
                if ($write['table'] !== 'audit_logs' || $write['call'] !== 'insert') {
                    continue;
                }

                $writers++;
                $supplied = array_map(strtolower(...), array_column($write['keys'], 0));

                foreach (self::AUDIT_CORE_COLUMNS as $column) {
                    if (! in_array($column, $supplied, true)) {
                        $findings[] = $this->at($path, $write['line']) . "inserts an audit entry without '{$column}'";
                    }
                }
            }
        }

        // A scan that found no writer would pass while proving nothing.
        $this->assertGreaterThanOrEqual(8, $writers, 'the scan must find the audit writers');
        $this->assertSame([], $findings, $this->report($findings));
    }

    /**
     * The restore wizard's curated section map is a hand-maintained list of table
     * names; a stale entry there means a subsystem silently restores nothing.
     */
    public function testTheCuratedRestoreSectionsMatchTheSchema(): void
    {
        $sections = (new \ReflectionClass(\App\Controllers\Backup::class))->getConstant('RESTORE_SECTIONS');

        $this->assertIsArray($sections);
        $this->assertGreaterThanOrEqual(8, count($sections), 'the restore wizard must still offer its sections');

        $findings = [];

        foreach ($sections as $section => $tables) {
            foreach ((array) $tables as $table) {
                if (is_string($table) && ! array_key_exists($table, $this->schema())) {
                    $findings[] = "Backup::RESTORE_SECTIONS['{$section}'] names '{$table}', which is not a table";
                }
            }
        }

        $this->assertSame([], $findings, $this->report($findings));
    }

    // ------------------------------------------------------------------

    /**
     * Application PHP files that name schema objects. Migrations are excluded:
     * they *are* the schema, they create tables in their own order, and their
     * `down()` methods drop what `up()` built.
     *
     * @return list<string>
     */
    private function schemaReferencingFiles(): array
    {
        $files    = [];
        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator(ROOTPATH . 'app', \FilesystemIterator::SKIP_DOTS)
        );

        foreach ($iterator as $file) {
            $path = str_replace('\\', '/', $file->getPathname());

            if ($file->getExtension() !== 'php' || str_contains($path, '/app/Database/Migrations/')) {
                continue;
            }

            $files[] = $path;
        }

        sort($files);

        $this->assertNotSame([], $files, 'the reference scan must find application files');

        return $files;
    }

    /**
     * Every call in a file whose first argument is a string literal, with the
     * chain of receiver names that leads to it.
     *
     * Tokenised rather than pattern-matched, so a column name inside a comment,
     * a heredoc or a string that merely looks like a query is not mistaken for a
     * real call. The chain is what distinguishes `$db->table('x')->set('col')`
     * (a column write) from `session()->set('col')` (a row key).
     *
     * @return list<array{0: string, 1: string, 2: int, 3: list<string>}> name, literal, line, receiver chain
     */
    private function literalCallArgs(string $path): array
    {
        $tokens = token_get_all((string) file_get_contents($path));
        $count  = count($tokens);
        $calls  = [];

        for ($i = 0; $i < $count; $i++) {
            $token = $tokens[$i];

            if (! is_array($token) || $token[0] !== T_STRING) {
                continue;
            }

            $open = $this->nextMeaningful($tokens, $i + 1);
            if ($open === null || $tokens[$open] !== '(') {
                continue;
            }

            $arg = $this->nextMeaningful($tokens, $open + 1);
            if ($arg === null || ! is_array($tokens[$arg]) || $tokens[$arg][0] !== T_CONSTANT_ENCAPSED_STRING) {
                continue;
            }

            $receiver = $this->receiverOf($tokens, $i);

            $calls[] = [
                strtolower($token[1]),
                $this->literalValue($tokens[$arg][1]),
                (int) $token[2],
                $receiver['chain'],
                $receiver['table'],
            ];
            unset($receiver);
        }

        return $calls;
    }

    /**
     * Every string key of an array literal passed as a call's first argument.
     *
     * One entry per array literal, with every key it declares. Grouped rather
     * than flattened because a *set* of keys is what a write needs: an insert is
     * only complete if the array as a whole carries the required columns.
     *
     * @return list<array{call: string, keys: list<array{0: string, 1: int}>, line: int, chain: list<string>, table: string|null}>
     */
    private function literalArrayWrites(string $path): array
    {
        $tokens = token_get_all((string) file_get_contents($path));
        $count  = count($tokens);
        $writes = [];

        for ($i = 0; $i < $count; $i++) {
            $token = $tokens[$i];

            if (! is_array($token) || $token[0] !== T_STRING) {
                continue;
            }

            $open = $this->nextMeaningful($tokens, $i + 1);
            if ($open === null || $tokens[$open] !== '(') {
                continue;
            }

            $bounds = $this->arrayLiteralBounds($tokens, $this->nextMeaningful($tokens, $open + 1));
            if ($bounds === null) {
                continue;
            }

            $keys = $this->stringKeysWithin($tokens, $bounds[0], $bounds[1]);
            if ($keys === []) {
                continue;
            }

            $receiver = $this->receiverOf($tokens, $i);

            $writes[] = [
                'call'  => strtolower($token[1]),
                'keys'  => $keys,
                'line'  => (int) $token[2],
                'chain' => $receiver['chain'],
                'table' => $receiver['table'],
            ];
        }

        return $writes;
    }

    /**
     * The brackets bounding an array literal, in either the `[...]` or
     * `array(...)` form. Anything else (a variable, a call, a spread) is not
     * statically readable and is skipped.
     *
     * @param list<array<int, int|string>|string> $tokens
     *
     * @return array{0: int, 1: int}|null opening and closing index
     */
    private function arrayLiteralBounds(array $tokens, ?int $start): ?array
    {
        if ($start === null) {
            return null;
        }

        if ($tokens[$start] === '[') {
            $close = $this->matchingDelimiter($tokens, $start, '[', ']');

            return $close === null ? null : [$start, $close];
        }

        if (is_array($tokens[$start]) && $tokens[$start][0] === T_ARRAY) {
            $paren = $this->nextMeaningful($tokens, $start + 1);
            if ($paren === null || $tokens[$paren] !== '(') {
                return null;
            }

            $close = $this->matchingDelimiter($tokens, $paren, '(', ')');

            return $close === null ? null : [$paren, $close];
        }

        return null;
    }

    /**
     * String keys at the top level of an array body — `'col' =>` — skipping the
     * keys of nested arrays, which belong to other tables or to JSON payloads.
     *
     * @param list<array<int, int|string>|string> $tokens
     *
     * @return list<array{0: string, 1: int}>
     */
    private function stringKeysWithin(array $tokens, int $from, int $to): array
    {
        $keys  = [];
        $depth = 0;

        for ($i = $from; $i <= $to; $i++) {
            $token = $tokens[$i];

            if ($token === '[' || $token === '(' || $token === '{') {
                $depth++;
                continue;
            }

            if ($token === ']' || $token === ')' || $token === '}') {
                $depth--;
                continue;
            }

            if ($depth !== 1 || ! is_array($token) || $token[0] !== T_CONSTANT_ENCAPSED_STRING) {
                continue;
            }

            $next = $this->nextMeaningful($tokens, $i + 1);

            if ($next !== null && is_array($tokens[$next]) && $tokens[$next][0] === T_DOUBLE_ARROW) {
                $keys[] = [$this->literalValue($token[1]), (int) $token[2]];
            }
        }

        return $keys;
    }

    /**
     * @param list<array<int, int|string>|string> $tokens
     */
    private function matchingDelimiter(array $tokens, int $open, string $openChar, string $closeChar): ?int
    {
        $depth = 0;

        for ($i = $open; $i < count($tokens); $i++) {
            if ($tokens[$i] === $openChar) {
                $depth++;
                continue;
            }

            if ($tokens[$i] === $closeChar && --$depth === 0) {
                return $i;
            }
        }

        return null;
    }

    /**
     * The literals a file asks about instead of assuming, read from
     * `fieldExists('x')`, `in_array('x', $fields)`, `array_key_exists('x', $row)`
     * and, when asked for, `tableExists('x')`.
     *
     * @param list<array{0: string, 1: string, 2: int, 3: list<string>}> $calls
     * @param list<string>                                              $probes which probe calls to read
     *
     * @return array<string, true>
     */
    private function presenceProbes(array $calls, array $probes = self::PRESENCE_PROBES): array
    {
        $probed = [];

        foreach ($calls as [$call, $literal]) {
            if (in_array($call, $probes, true)) {
                $probed[$literal] = true;
            }
        }

        return $probed;
    }

    /**
     * `session()->set('key', ...)` and `view()->set('key', ...)` write a row key
     * or a view variable, not a database column.
     *
     * @param list<string> $chain
     */
    private function writesARowKey(array $chain): bool
    {
        foreach ($chain as $receiver) {
            if (in_array($receiver, self::NON_COLUMN_SETTERS, true)) {
                return true;
            }
        }

        return false;
    }

    /**
     * The names a call is chained onto, innermost last: for the `set` in
     * `$db->table('x')->set('col', ...)` that is ['table', 'db']. Variables are
     * reported without their sigil, so `$session->set()` and `session()->set()`
     * both read as 'session'.
     *
     * @param list<array<int, int|string>|string> $tokens
     *
     * @return list<string>
     */
    private function chainBefore(array $tokens, int $call): array
    {
        return $this->receiverOf($tokens, $call)['chain'];
    }

    /**
     * The receiver a call hangs off: its chain of names, and — when the chain
     * passes through `table('x')` or `from('x')` — the table being written, which
     * is what lets a write be judged against *its* table rather than any table.
     *
     * @param list<array<int, int|string>|string> $tokens
     *
     * @return array{chain: list<string>, table: string|null}
     */
    private function receiverOf(array $tokens, int $call): array
    {
        $chain = [];
        $table = null;
        $i     = $call;

        while (true) {
            $operator = $this->prevMeaningful($tokens, $i - 1);

            if ($operator === null || ! is_array($tokens[$operator]) || ! in_array($tokens[$operator][0], [T_OBJECT_OPERATOR, T_NULLSAFE_OBJECT_OPERATOR], true)) {
                return ['chain' => $chain, 'table' => $table];
            }

            $target = $this->prevMeaningful($tokens, $operator - 1);
            if ($target === null) {
                return ['chain' => $chain, 'table' => $table];
            }

            // `a()->b(...)`: step back over the argument list to the call name.
            if ($tokens[$target] === ')') {
                $open = $this->matchingOpen($tokens, $target);
                if ($open === null) {
                    return ['chain' => $chain, 'table' => $table];
                }

                $target = $this->prevMeaningful($tokens, $open - 1);
                if ($target === null) {
                    return ['chain' => $chain, 'table' => $table];
                }
            }

            $token = $tokens[$target];

            if (is_array($token) && $token[0] === T_STRING) {
                $name    = strtolower($token[1]);
                $chain[] = $name;
                $i       = $target;

                if (($name === 'table' || $name === 'from') && $table === null) {
                    $table = $this->firstLiteralArg($tokens, $target);
                }

                continue;
            }

            if (is_array($token) && $token[0] === T_VARIABLE) {
                $chain[] = strtolower(ltrim($token[1], '$'));

                return ['chain' => $chain, 'table' => $table];
            }

            return ['chain' => $chain, 'table' => $table];
        }
    }

    /**
     * The first string literal argument of a call, if that is what it is.
     *
     * @param list<array<int, int|string>|string> $tokens
     */
    private function firstLiteralArg(array $tokens, int $callName): ?string
    {
        $open = $this->nextMeaningful($tokens, $callName + 1);
        if ($open === null || $tokens[$open] !== '(') {
            return null;
        }

        $arg = $this->nextMeaningful($tokens, $open + 1);
        if ($arg === null || ! is_array($tokens[$arg]) || $tokens[$arg][0] !== T_CONSTANT_ENCAPSED_STRING) {
            return null;
        }

        return $this->literalValue($tokens[$arg][1]);
    }

    /**
     * @param list<array<int, int|string>|string> $tokens
     */
    private function matchingOpen(array $tokens, int $close): ?int
    {
        $depth = 0;

        for ($i = $close; $i >= 0; $i--) {
            if ($tokens[$i] === ')') {
                $depth++;
                continue;
            }

            if ($tokens[$i] === '(' && --$depth === 0) {
                return $i;
            }
        }

        return null;
    }

    /**
     * @param list<array<int, int|string>|string> $tokens
     */
    private function prevMeaningful(array $tokens, int $from): ?int
    {
        for ($i = $from; $i >= 0; $i--) {
            if (is_array($tokens[$i]) && in_array($tokens[$i][0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)) {
                continue;
            }

            return $i;
        }

        return null;
    }

    /**
     * @param list<array<int, int|string>|string> $tokens
     */
    private function nextMeaningful(array $tokens, int $from): ?int
    {
        for ($i = $from; $i < count($tokens); $i++) {
            $token = $tokens[$i];

            if (is_array($token) && in_array($token[0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)) {
                continue;
            }

            return $i;
        }

        return null;
    }

    private function literalValue(string $raw): string
    {
        $inner = substr($raw, 1, -1);

        return str_replace(["\\'", '\\\\'], ["'", '\\'], $inner);
    }

    /**
     * Every column name in the schema, lowercased.
     *
     * @return array<string, true>
     */
    private function allColumns(): array
    {
        $columns = [];

        foreach ($this->schema() as $names) {
            foreach ($names as $name) {
                $columns[strtolower($name)] = true;
            }
        }

        return $columns;
    }

    private function at(string $path, int $line): string
    {
        $relative = str_replace('\\', '/', str_replace(ROOTPATH, '', $path));

        return $relative . ':' . $line . ' ';
    }

    /**
     * @return list<string>
     */
    private function modelClasses(): array
    {
        $classes = [];

        foreach (glob(ROOTPATH . 'app/Models/*.php') ?: [] as $file) {
            $class = 'App\\Models\\' . basename($file, '.php');

            if (class_exists($class)) {
                $classes[] = $class;
            }
        }

        sort($classes);

        return $classes;
    }

    /**
     * @return list<string>
     */
    private function inspect(string $class): array
    {
        $props = (new \ReflectionClass($class))->getDefaultProperties();

        $table = is_string($props['table'] ?? null) ? $props['table'] : '';
        if ($table === '') {
            return [$this->finding($class, 'declares no $table, so it has no schema to match')];
        }

        $columns = $this->columnsOf($table);

        if ($columns === null) {
            return [$this->finding($class, "table '{$table}' does not exist in the migrated schema")];
        }

        $findings = [];

        $primaryKey = is_string($props['primaryKey'] ?? null) ? $props['primaryKey'] : '';
        if ($primaryKey !== '' && ! in_array($primaryKey, $columns, true)) {
            $findings[] = $this->finding($class, "\$primaryKey '{$primaryKey}' is not a column of '{$table}'");
        }

        foreach ((array) ($props['allowedFields'] ?? []) as $field) {
            if (is_string($field) && $field !== '' && ! in_array($field, $columns, true)) {
                $findings[] = $this->finding($class, "\$allowedFields names '{$field}', which '{$table}' does not have");
            }
        }

        if (($props['useTimestamps'] ?? false) === true) {
            foreach (['createdField', 'updatedField'] as $property) {
                $field = is_string($props[$property] ?? null) && $props[$property] !== ''
                    ? $props[$property]
                    : ($property === 'createdField' ? 'created_at' : 'updated_at');

                if (! in_array($field, $columns, true)) {
                    $findings[] = $this->finding($class, "\$useTimestamps is on but '{$table}' has no '{$field}' column");
                }
            }
        }

        if (($props['useSoftDeletes'] ?? false) === true) {
            $field = is_string($props['deletedField'] ?? null) && $props['deletedField'] !== ''
                ? $props['deletedField']
                : 'deleted_at';

            if (! in_array($field, $columns, true)) {
                $findings[] = $this->finding($class, "\$useSoftDeletes is on but '{$table}' has no '{$field}' column");
            }
        }

        if (($props['useAutoIncrement'] ?? false) === true && $primaryKey !== '') {
            $type = $this->typeOf($table, $primaryKey);

            if ($type !== null && ! $this->isIntegerType($type)) {
                $findings[] = $this->finding(
                    $class,
                    "\$useAutoIncrement is on but '{$table}.{$primaryKey}' is {$type}; the column cannot generate a value"
                );
            }
        }

        foreach ((array) ($props['casts'] ?? []) as $field => $cast) {
            if (is_string($field) && ! in_array($field, $columns, true) && $field !== '*') {
                $findings[] = $this->finding($class, "\$casts names '{$field}', which '{$table}' does not have");
            }
        }

        foreach ((array) ($props['validationRules'] ?? []) as $field => $rules) {
            if (is_string($field) && $field !== '' && ! in_array($field, $columns, true)) {
                $findings[] = $this->finding($class, "\$validationRules names '{$field}', which '{$table}' does not have");
            }
        }

        return $findings;
    }

    /**
     * @return list<string>|null
     */
    private function columnsOf(string $table): ?array
    {
        $schema = $this->schema();

        return $schema[$table] ?? null;
    }

    /**
     * The columns a table cannot be inserted into without supplying a value:
     * neither nullable nor defaulted nor the primary key.
     *
     * @return list<string>|null null when the table is not in the schema
     */
    private function requiredColumns(string $table): ?array
    {
        if (! array_key_exists($table, $this->schema())) {
            return null;
        }

        $required = [];

        foreach ($this->db->getFieldData($table) as $field) {
            if (($field->primary_key ?? false) === true) {
                continue;
            }

            if (($field->nullable ?? false) === true || ($field->default ?? null) !== null) {
                continue;
            }

            $required[] = $field->name;
        }

        return $required;
    }

    private function typeOf(string $table, string $column): ?string
    {
        $field = $this->db->getFieldData($table);
        foreach ($field as $f) {
            if ($f->name === $column) {
                return strtoupper((string) $f->type);
            }
        }

        return null;
    }

    private function isIntegerType(string $type): bool
    {
        foreach (['INT', 'INTEGER', 'BIGINT', 'SMALLINT', 'TINYINT', 'MEDIUMINT', 'SERIAL'] as $needle) {
            if (str_contains($type, $needle)) {
                return true;
            }
        }

        return false;
    }

    /**
     * Every table the migrated schema defines, with its columns. Built once.
     *
     * @return array<string, list<string>>
     */
    private function schema(): array
    {
        if ($this->schema !== null) {
            return $this->schema;
        }

        $schema = [];

        foreach ($this->db->listTables() as $raw) {
            // `listTables()` reports the physical name, which carries the test
            // prefix; models declare the logical one. `getFieldData()` wants the
            // logical name too, because it applies the prefix itself.
            $logical = $this->logicalTable((string) $raw);

            $columns = [];
            foreach ($this->db->getFieldData($logical) as $field) {
                $columns[] = $field->name;
            }

            $schema[$logical] = $columns;
        }

        return $this->schema = $schema;
    }

    private function logicalTable(string $table): string
    {
        $prefix = (string) $this->db->DBPrefix;

        return $prefix !== '' && str_starts_with($table, $prefix)
            ? substr($table, strlen($prefix))
            : $table;
    }

    private function finding(string $class, string $problem): string
    {
        return str_replace('App\\Models\\', '', $class) . ': ' . $problem;
    }

    /**
     * @param list<string> $findings
     */
    private function report(array $findings): string
    {
        if ($findings === []) {
            return '';
        }

        return count($findings) . " model/schema mismatch(es):\n  - " . implode("\n  - ", $findings);
    }
}
