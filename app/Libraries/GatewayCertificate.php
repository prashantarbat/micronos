<?php

namespace App\Libraries;

use App\Models\PkiAuthorityModel;
use App\Models\PkiCertificateModel;

/**
 * GatewayCertificate — the TLS certificate the Clientless Gateway presents.
 *
 * The certificate itself lives in the PKI store (`pki_certificates`), so an
 * uploaded or Let's Encrypt certificate is managed like any other one;
 * `ztna_settings.cert_id` says which one the gateway uses (0 = the self-signed
 * pair micrond generates). Installing it means writing the full chain and key to
 * /etc/micron/pki/ztna.{crt,key}, which nginx reads, through `cert.install`.
 *
 * {@see self::redeployBindings()} is what keeps renewals live: the files on
 * disk are copies, so a renewed certificate has to be written out again for
 * every service that is bound to it.
 */
final class GatewayCertificate
{
    private $ipc;

    public function __construct($ipc = null)
    {
        $this->ipc = $ipc ?? \Config\Services::ipc();
    }

    /**
     * Certificates the gateway can use: server certificates with a private key.
     *
     * @return list<array<string, mixed>>
     */
    public function candidates(): array
    {
        return (new PkiCertificateModel())
            ->select('id, name, common_name, san_dns, valid_until, source')
            ->where('revoked', 0)
            ->where('cert_type', 'server')
            ->where('private_key !=', '')
            ->orderBy('name', 'ASC')
            ->findAll();
    }

    /**
     * What the gateway is presenting, for the settings page.
     *
     * @return array{cert_id: int, name: string, common_name: string, issuer: string, source: string, valid_until: ?string, days_left: ?int, covers_domain: bool, self_signed: bool}
     */
    public function status(int $certId, string $domain): array
    {
        $cert = $certId > 0 ? (new PkiCertificateModel())->find($certId) : null;

        if (! is_array($cert)) {
            return [
                'cert_id'       => 0,
                'name'          => 'Self-signed (generated by the appliance)',
                'common_name'   => 'micronos-ztna',
                'issuer'        => 'self-signed',
                'source'        => 'self-signed',
                'valid_until'   => null,
                'days_left'     => null,
                'covers_domain' => false,
                'self_signed'   => true,
            ];
        }

        $parsed   = X509::parseCertificate((string) $cert['certificate']);
        $until    = $cert['valid_until'] ?: ($parsed['valid_until'] ?? null);
        $daysLeft = $until ? (int) floor((strtotime((string) $until) - time()) / 86400) : null;

        return [
            'cert_id'       => (int) $cert['id'],
            'name'          => (string) $cert['name'],
            'common_name'   => (string) $cert['common_name'],
            'issuer'        => (string) ($parsed['issuer_cn'] ?? ''),
            'source'        => (string) ($cert['source'] ?? 'generated'),
            'valid_until'   => $until ? (string) $until : null,
            'days_left'     => $daysLeft,
            'covers_domain' => self::covers((string) $cert['common_name'], (string) ($cert['san_dns'] ?? ''), $domain),
            'self_signed'   => false,
        ];
    }

    /**
     * Install a PKI certificate (or the self-signed fallback when $certId is 0)
     * as the gateway certificate.
     *
     * @return array{ok: bool, message: string}
     */
    public function deploy(int $certId, string $domain): array
    {
        if ($certId <= 0) {
            $res = $this->ipc->call('cert.install', [
                'service'     => 'ztna',
                'self_signed' => true,
                'domain'      => $domain,
            ]);

            return self::outcome($res, 'Self-signed gateway certificate generated for ' . $domain . '.');
        }

        $cert = (new PkiCertificateModel())->find($certId);
        if (! is_array($cert) || ! empty($cert['revoked'])) {
            return ['ok' => false, 'message' => 'That certificate no longer exists or has been revoked.'];
        }
        if (trim((string) $cert['private_key']) === '') {
            return ['ok' => false, 'message' => 'That certificate has no private key, so the gateway cannot use it.'];
        }

        $res = $this->ipc->call('cert.install', [
            'service'  => 'ztna',
            'cert_pem' => self::fullChain($cert),
            'key_pem'  => (string) $cert['private_key'],
        ]);

        return self::outcome($res, 'Certificate "' . $cert['name'] . '" is now installed on the gateway.');
    }

    /**
     * Import an uploaded certificate (plus optional intermediate chain) into the
     * PKI store.
     *
     * @return array{ok: bool, message: string, cert_id?: int}
     */
    public function import(string $certText, string $keyText, string $chainText, string $name = ''): array
    {
        $blocks = self::pemBlocks($certText);
        if ($blocks === []) {
            return ['ok' => false, 'message' => 'The certificate is not a readable PEM certificate.'];
        }

        // A full-chain file in the certificate field is accepted: the first block
        // is the server certificate, the rest is the chain.
        $leaf  = array_shift($blocks);
        $chain = array_merge($blocks, self::pemBlocks($chainText));

        $meta = X509::parseCertificate($leaf);
        if ($meta === null) {
            return ['ok' => false, 'message' => 'The certificate could not be parsed.'];
        }

        $key = X509::normalizeKey($keyText);
        if ($key === null) {
            return ['ok' => false, 'message' => 'The private key is not a readable PEM key (an encrypted key must be decrypted first).'];
        }
        if (! X509::keyMatchesCertificate($key, $meta['certificate'])) {
            return ['ok' => false, 'message' => 'The private key does not match the certificate.'];
        }
        if (! empty($meta['valid_until']) && strtotime((string) $meta['valid_until']) < time()) {
            return ['ok' => false, 'message' => 'The certificate expired on ' . $meta['valid_until'] . '.'];
        }

        $caId = $chain !== [] ? $this->chainAuthority($chain) : $this->knownIssuer((string) $meta['issuer_cn']);

        $name = trim($name);
        if ($name === '') {
            $name = 'Clientless Gateway: ' . ($meta['common_name'] !== '' ? $meta['common_name'] : 'uploaded');
        }

        $certModel = new PkiCertificateModel();
        $id = (int) $certModel->insert([
            'ca_id'         => $caId,
            'cert_type'     => 'server',
            'name'          => mb_substr($name, 0, 100),
            'common_name'   => mb_substr($meta['common_name'] !== '' ? $meta['common_name'] : $name, 0, 128),
            'organization'  => $meta['organization'],
            'san_dns'       => $meta['san_dns'],
            'san_ip'        => $meta['san_ip'],
            'certificate'   => $meta['certificate'],
            'private_key'   => $key,
            'serial_number' => $meta['serial_number'] !== '' ? $meta['serial_number'] : '',
            'valid_from'    => $meta['valid_from'] ?? date('Y-m-d H:i:s'),
            'valid_until'   => $meta['valid_until'] ?? date('Y-m-d H:i:s'),
            'revoked'       => 0,
            'description'   => 'Uploaded for the Clientless Gateway',
            'source'        => 'imported',
        ]);

        if ($id <= 0) {
            return ['ok' => false, 'message' => 'The certificate could not be stored: ' . implode('; ', $certModel->errors())];
        }

        return ['ok' => true, 'message' => 'Certificate imported.', 'cert_id' => $id];
    }

    /**
     * Re-install a renewed certificate everywhere it is bound.
     *
     * Called after ACME issues or renews a certificate in place. Services read
     * copies of the PEM files, so without this a renewal never reaches them.
     */
    public static function redeployBindings(int $certId, $ipc = null): void
    {
        if ($certId <= 0) {
            return;
        }

        try {
            $db = \Config\Database::connect();

            if ($db->tableExists('ztna_settings')) {
                $row = $db->table('ztna_settings')->select('cert_id, external_domain')->where('id', 1)->get()->getRowArray();
                if (is_array($row) && (int) ($row['cert_id'] ?? 0) === $certId) {
                    (new self($ipc))->deploy($certId, (string) ($row['external_domain'] ?? ''));
                }
            }

            if ($db->tableExists('system_settings') && $db->fieldExists('webgui_cert_id', 'system_settings')) {
                $row = $db->table('system_settings')->select('webgui_cert_id')->where('id', 1)->get()->getRowArray();
                if (is_array($row) && (int) ($row['webgui_cert_id'] ?? 0) === $certId) {
                    $cert = (new PkiCertificateModel())->find($certId);
                    if (is_array($cert)) {
                        (new ConfigApplier($ipc))->webguiCertificate(['certificate' => self::fullChain($cert)] + $cert);
                    }
                }
            }
        } catch (\Throwable $e) {
            log_message('error', '[GatewayCertificate] redeploying certificate ' . $certId . ' failed: ' . $e->getMessage());
        }
    }

    /** The certificate followed by its issuer chain, which is what nginx needs. */
    public static function fullChain(array $cert): string
    {
        $pem = trim((string) $cert['certificate']) . "\n";

        $caId = (int) ($cert['ca_id'] ?? 0);
        if ($caId > 0) {
            $ca = (new PkiAuthorityModel())->find($caId);
            $chain = is_array($ca) ? trim((string) ($ca['certificate'] ?? '')) : '';
            if ($chain !== '' && ! str_contains($pem, $chain)) {
                $pem .= $chain . "\n";
            }
        }

        return $pem;
    }

    /** Whether a certificate's names include the gateway hostname. */
    public static function covers(string $commonName, string $sanDns, string $domain): bool
    {
        $domain = strtolower(trim($domain));
        if ($domain === '') {
            return false;
        }

        $names = array_filter(array_map(
            static fn ($n) => strtolower(trim($n)),
            array_merge([$commonName], explode(',', $sanDns))
        ));

        foreach ($names as $name) {
            if ($name === $domain) {
                return true;
            }
            if (str_starts_with($name, '*.') && substr_count($domain, '.') >= 2
                && substr($domain, strpos($domain, '.')) === substr($name, 1)) {
                return true;
            }
        }

        return false;
    }

    /** @return list<string> every CERTIFICATE block in the text, normalised */
    private static function pemBlocks(string $text): array
    {
        preg_match_all('/-----BEGIN CERTIFICATE-----.+?-----END CERTIFICATE-----/s', $text, $m);

        $out = [];
        foreach ($m[0] as $block) {
            $pem = X509::normalizePem($block, 'CERTIFICATE');
            if ($pem !== null) {
                $out[] = $pem;
            }
        }

        return $out;
    }

    /** Record an uploaded intermediate chain as a key-less authority row. */
    private function chainAuthority(array $chain): int
    {
        $first = X509::parseCertificate($chain[0]);
        if ($first === null) {
            return 0;
        }

        $model = new PkiAuthorityModel();
        $cn    = (string) ($first['common_name'] ?: 'Uploaded issuer');
        $pem   = implode("\n", array_map('trim', $chain));

        $existing = $model->where('common_name', $cn)->first();
        if (is_array($existing)) {
            // Never overwrite an authority this appliance can sign with.
            if (trim((string) ($existing['private_key'] ?? '')) === '') {
                $model->update((int) $existing['id'], ['certificate' => $pem]);
            }

            return (int) $existing['id'];
        }

        return (int) $model->insert([
            'name'          => mb_substr($cn, 0, 100),
            'common_name'   => mb_substr($cn, 0, 128),
            'organization'  => (string) ($first['organization'] ?? ''),
            'country'       => '',
            'state'         => '',
            'city'          => '',
            'certificate'   => $pem,
            'private_key'   => '',
            'serial_number' => (string) ($first['serial_number'] ?: '0'),
            'valid_from'    => $first['valid_from'] ?? null,
            'valid_until'   => $first['valid_until'] ?? null,
            'key_length'    => 0,
            'digest'        => 'sha256',
            'is_default'    => 0,
            'source'        => 'imported',
        ]);
    }

    private function knownIssuer(string $issuerCn): int
    {
        if ($issuerCn === '') {
            return 0;
        }
        $match = (new PkiAuthorityModel())->where('common_name', $issuerCn)->first();

        return is_array($match) ? (int) $match['id'] : 0;
    }

    private static function outcome(array $res, string $okMessage): array
    {
        $result = $res['result'] ?? null;
        if (! empty($res['error'])) {
            return ['ok' => false, 'message' => 'micrond refused the certificate: ' . ($res['error']['message'] ?? 'unknown error')];
        }
        if (is_array($result) && array_key_exists('success', $result) && ! $result['success']) {
            return ['ok' => false, 'message' => 'The certificate was not installed: ' . ($result['message'] ?? 'unknown error')];
        }

        return ['ok' => true, 'message' => $okMessage];
    }
}
