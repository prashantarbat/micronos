<?php

namespace App\Libraries;

use App\Models\CaptiveWalledGardenModel;
use App\Models\CaptiveZoneModel;

/**
 * CaptiveCompiler — Translates Captive Zone definitions and Walled Gardens
 * into deterministic Linux Netfilter (nftables) configuration rulesets.
 */
class CaptiveCompiler
{
    protected CaptiveZoneModel $zoneModel;
    protected CaptiveWalledGardenModel $walledGardenModel;

    public function __construct(
        ?CaptiveZoneModel $zoneModel = null,
        ?CaptiveWalledGardenModel $walledGardenModel = null
    ) {
        $this->zoneModel         = $zoneModel ?? new CaptiveZoneModel();
        $this->walledGardenModel = $walledGardenModel ?? new CaptiveWalledGardenModel();
    }

    /**
     * Standard built-in Walled Garden IP subnets for Captive Network Assistant (CNA)
     * auto-detection triggers on iOS, Android, and Windows.
     */
    public const DEFAULT_CNA_PREFIXES = [
        '17.0.0.0/8',      // Apple Captive & CDN infrastructure
        '142.250.0.0/15',  // Google connectivitycheck.gstatic.com
        '20.0.0.0/11',     // Microsoft NCSI & Windows Connect Test
        '52.96.0.0/12',    // Microsoft Connectivity Endpoints
    ];

    /**
     * Compiles the complete captive portal nftables configuration snippet.
     *
     * @return string Valid nftables syntax
     */
    public function compile(): string
    {
        $zones = $this->zoneModel->where('enabled', 1)->findAll();

        $out = "# ==============================================================================\n";
        $out .= "# Micron OS — Captive Portal & Guest Redirection Ruleset (Generated by CaptiveCompiler)\n";
        $out .= "# ==============================================================================\n\n";

        if (empty($zones)) {
            $out .= "# No active captive zones configured.\n";
            return $out;
        }

        $out .= "table inet filter {\n";

        // 1. Declare Sets per Zone
        foreach ($zones as $zone) {
            $tag = $this->sanitizeTag($zone['slug'] ?: $zone['id']);

            // MAC authorized set (with kernel-managed expiry)
            $out .= "    set captive_mac_{$tag} {\n";
            $out .= "        type ether_addr\n";
            $out .= "        flags timeout\n";
            $out .= "    }\n\n";

            // IPv4 authorized set (with kernel-managed expiry)
            $out .= "    set captive_ip_{$tag} {\n";
            $out .= "        type ipv4_addr\n";
            $out .= "        flags timeout\n";
            $out .= "    }\n\n";

            // Walled Garden IP interval set
            $walledTargets = $this->resolveWalledGardenIps($zone['id']);
            $out .= "    set captive_walled_{$tag} {\n";
            $out .= "        type ipv4_addr\n";
            $out .= "        flags interval\n";
            if (!empty($walledTargets)) {
                $out .= "        elements = { " . implode(', ', $walledTargets) . " }\n";
            }
            $out .= "    }\n\n";
        }

        // 2. Prerouting Redirection Chain
        $out .= "    chain captive_prerouting {\n";
        $out .= "        type nat hook prerouting priority dstnat - 5; policy accept;\n";

        foreach ($zones as $zone) {
            $iface = trim($zone['interface_id']);
            if (empty($iface)) {
                continue;
            }

            $tag      = $this->sanitizeTag($zone['slug'] ?: $zone['id']);
            $httpPort = (int) ($zone['portal_port'] ?: 8088);
            $sslPort  = (int) ($zone['portal_ssl_port'] ?: 8443);

            $out .= "\n        # Zone: {$zone['name']} ({$iface})\n";
            $out .= "        iifname \"{$iface}\" ether saddr @captive_mac_{$tag} accept\n";
            $out .= "        iifname \"{$iface}\" ip saddr @captive_ip_{$tag} accept\n";
            $out .= "        iifname \"{$iface}\" ip daddr @captive_walled_{$tag} accept\n";
            $out .= "        iifname \"{$iface}\" tcp dport 80 redirect to :{$httpPort}\n";
            $out .= "        iifname \"{$iface}\" tcp dport 443 redirect to :{$sslPort}\n";
        }

        $out .= "    }\n\n";

        // 3. Forwarding Filter Chain
        $out .= "    chain captive_forward {\n";
        $out .= "        type filter hook forward priority filter + 5; policy accept;\n";

        foreach ($zones as $zone) {
            $iface = trim($zone['interface_id']);
            if (empty($iface)) {
                continue;
            }

            $tag = $this->sanitizeTag($zone['slug'] ?: $zone['id']);

            $out .= "\n        # Zone: {$zone['name']} ({$iface}) Unauthenticated Drop Guard\n";
            $out .= "        iifname \"{$iface}\" ether saddr @captive_mac_{$tag} accept\n";
            $out .= "        iifname \"{$iface}\" ip saddr @captive_ip_{$tag} accept\n";
            $out .= "        iifname \"{$iface}\" ip daddr @captive_walled_{$tag} accept\n";
            $out .= "        iifname \"{$iface}\" drop\n";
        }

        $out .= "    }\n";
        $out .= "}\n";

        return $out;
    }

    /**
     * Resolves all walled garden IP/CIDR elements for a zone, including standard CNA endpoints.
     *
     * @return array<string>
     */
    public function resolveWalledGardenIps(string $zoneId): array
    {
        $elements = self::DEFAULT_CNA_PREFIXES;

        $dbTargets = $this->walledGardenModel->getEnabledTargets($zoneId);
        foreach ($dbTargets as $item) {
            $target = trim($item['target']);
            if (empty($target)) {
                continue;
            }

            // Check if valid IPv4 address or CIDR
            if (filter_var(explode('/', $target)[0], FILTER_VALIDATE_IP, FILTER_FLAG_IPV4)) {
                $elements[] = $target;
            } elseif (filter_var($target, FILTER_VALIDATE_DOMAIN, FILTER_FLAG_HOSTNAME)) {
                // If hostname, attempt lightweight local DNS resolution
                $resolved = @gethostbynamel($target);
                if (!empty($resolved)) {
                    foreach ($resolved as $ip) {
                        if (filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4)) {
                            $elements[] = $ip;
                        }
                    }
                }
            }
        }

        return array_values(array_unique($elements));
    }

    /**
     * Sanitizes zone names into safe alphanumeric identifiers for nftables set/chain names.
     */
    public function sanitizeTag(string $name): string
    {
        $clean = preg_replace('/[^a-zA-Z0-9_]/', '_', strtolower($name));
        return substr((string) $clean, 0, 24);
    }
}
