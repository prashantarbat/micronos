<?php

namespace App\Libraries;

use App\Models\ZtnaResourceModel;
use App\Models\ZtnaSettingsModel;

/**
 * ZtnaCompiler — Compiles Nginx reverse proxy configuration for published
 * clientless web applications and Guacamole WebSocket tunnel endpoints.
 */
class ZtnaCompiler
{
    protected ZtnaResourceModel $resourceModel;
    protected ZtnaSettingsModel $settingsModel;

    public function __construct(
        ?ZtnaResourceModel $resourceModel = null,
        ?ZtnaSettingsModel $settingsModel = null
    ) {
        $this->resourceModel = $resourceModel ?? new ZtnaResourceModel();
        $this->settingsModel = $settingsModel ?? new ZtnaSettingsModel();
    }

    /**
     * Compile complete Nginx reverse proxy configuration artifact.
     *
     * @return array{enabled: bool, nginx_config: string, summary: array}
     */
    public function compile(): array
    {
        $settings = $this->settingsModel->getSettings();
        $enabled  = (bool) ($settings['enabled'] ?? true);

        if (!$enabled) {
            return [
                'enabled'      => false,
                'nginx_config' => "# Micron OS Clientless Gateway is DISABLED\n",
                'summary'      => ['resources_count' => 0, 'status' => 'disabled'],
            ];
        }

        $domain    = $settings['external_domain'] ?: 'gateway.micronos.local';
        $guacdHost = $settings['guacd_host'] ?: '127.0.0.1';
        $guacdPort = (int) ($settings['guacd_port'] ?: 4822);

        $resources = $this->resourceModel->orderBy('name', 'ASC')->findAll();

        $lines = [];
        $lines[] = "# ======================================================================";
        $lines[] = "# Micron OS Zero Trust Network Access (ZTNA) Clientless Gateway";
        $lines[] = "# Generated by ZtnaCompiler — Do Not Edit Manually";
        $lines[] = "# ======================================================================";
        $lines[] = "server {";
        $lines[] = "    listen 443 ssl http2;";
        $lines[] = "    server_name {$domain};";
        $lines[] = "";
        $lines[] = "    # Internal Identity Authentication Subrequest";
        $lines[] = "    location = /api/ztna/verify-auth {";
        $lines[] = "        internal;";
        $lines[] = "        proxy_pass http://127.0.0.1:80/vpn/clientless-gateway/verify-auth;";
        $lines[] = "        proxy_pass_request_body off;";
        $lines[] = "        proxy_set_header Content-Length \"\";";
        $lines[] = "        proxy_set_header X-Original-URI \$request_uri;";
        $lines[] = "        proxy_set_header X-Real-IP \$remote_addr;";
        $lines[] = "    }";
        $lines[] = "";
        $lines[] = "    # HTML5 Guacamole WebSocket Tunnel for In-Browser RDP/SSH/VNC";
        $lines[] = "    location /tunnel {";
        $lines[] = "        proxy_pass http://{$guacdHost}:{$guacdPort}/;";
        $lines[] = "        proxy_http_version 1.1;";
        $lines[] = "        proxy_set_header Upgrade \$http_upgrade;";
        $lines[] = "        proxy_set_header Connection \"upgrade\";";
        $lines[] = "        proxy_read_timeout 3600s;";
        $lines[] = "        proxy_send_timeout 3600s;";
        $lines[] = "    }";
        $lines[] = "";

        // Published Web Applications
        foreach ($resources as $res) {
            if ($res['type'] !== 'web') continue;

            $slug = $res['slug'];
            $host = $res['internal_host'];
            $port = $res['internal_port'];

            $lines[] = "    # Published App: {$res['name']} ({$slug})";
            $lines[] = "    location /apps/{$slug}/ {";
            $lines[] = "        auth_request /api/ztna/verify-auth;";
            $lines[] = "        auth_request_set \$remote_user \$upstream_http_x_remote_user;";
            $lines[] = "        auth_request_set \$remote_email \$upstream_http_x_remote_email;";
            $lines[] = "        auth_request_set \$remote_groups \$upstream_http_x_remote_groups;";
            $lines[] = "        proxy_pass http://{$host}:{$port}/;";
            $lines[] = "        proxy_set_header Host \$host;";
            $lines[] = "        proxy_set_header X-Real-IP \$remote_addr;";
            $lines[] = "        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;";
            $lines[] = "        proxy_set_header X-Remote-User \$remote_user;";
            $lines[] = "        proxy_set_header X-Remote-Email \$remote_email;";
            $lines[] = "        proxy_set_header X-Remote-Groups \$remote_groups;";
            $lines[] = "    }";
            $lines[] = "";
        }

        // Default root redirects to clientless portal
        $lines[] = "    location / {";
        $lines[] = "        proxy_pass http://127.0.0.1:80/vpn/clientless-gateway/portal;";
        $lines[] = "        proxy_set_header Host \$host;";
        $lines[] = "    }";
        $lines[] = "}";

        return [
            'enabled'      => true,
            'nginx_config' => implode("\n", $lines),
            'summary'      => [
                'resources_count' => count($resources),
                'domain'          => $domain,
                'status'          => 'active',
            ],
        ];
    }
}
