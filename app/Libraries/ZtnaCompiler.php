<?php

namespace App\Libraries;

use App\Models\ZtnaResourceModel;
use App\Models\ZtnaSettingsModel;

/**
 * ZtnaCompiler — Compiles Nginx reverse proxy configuration for published
 * clientless web applications and Guacamole WebSocket tunnel endpoints.
 */
class ZtnaCompiler
{
    /** Loopback port of micron-guacd-bridge (system/micron-guacd-bridge). */
    public const BRIDGE_PORT = 4823;

    /** WebSocket tunnel path, shared with the management UI's Apache vhost. */
    public const TUNNEL_PATH = '/vpn/clientless-gateway/tunnel';

    /**
     * Plain-HTTP listener for Let's Encrypt HTTP-01 validation. WAN port 80 is
     * redirected here by the firewall while a Let's Encrypt certificate is
     * enabled (NftablesCompiler), so the management UI on :80 is never exposed.
     */
    public const ACME_PORT = 8480;

    /** The management-plane web server every gateway page is served from. */
    private const UPSTREAM = 'http://127.0.0.1:80';

    protected ZtnaResourceModel $resourceModel;
    protected ZtnaSettingsModel $settingsModel;

    public function __construct(
        ?ZtnaResourceModel $resourceModel = null,
        ?ZtnaSettingsModel $settingsModel = null
    ) {
        $this->resourceModel = $resourceModel ?? new ZtnaResourceModel();
        $this->settingsModel = $settingsModel ?? new ZtnaSettingsModel();
    }

    /**
     * Compile complete Nginx reverse proxy configuration artifact.
     *
     * @return array{enabled: bool, nginx_config: string, summary: array}
     */
    public function compile(): array
    {
        $settings = $this->settingsModel->getSettings();
        $enabled  = (bool) ($settings['enabled'] ?? true);

        if (!$enabled) {
            return [
                'enabled'      => false,
                'nginx_config' => "# Micron OS Clientless Gateway is DISABLED\n",
                'summary'      => ['resources_count' => 0, 'status' => 'disabled'],
            ];
        }

        $domain       = $settings['external_domain'] ?: 'gateway.micronos.local';
        $externalPort = (int) ($settings['external_port'] ?: 443);
        $guacdHost    = $settings['guacd_host'] ?: '127.0.0.1';
        $guacdPort    = (int) ($settings['guacd_port'] ?: 4822);

        $resources = $this->resourceModel->orderBy('name', 'ASC')->findAll();
        $acme      = (int) ($settings['acme_enabled'] ?? 0) === 1;
        $httpsHost = '$host' . ($externalPort === 443 ? '' : ':' . $externalPort);

        $lines = [];
        $lines[] = "# ======================================================================";
        $lines[] = "# Micron OS Zero Trust Network Access (ZTNA) Clientless Gateway";
        $lines[] = "# Generated by ZtnaCompiler — Do Not Edit Manually";
        $lines[] = "# ======================================================================";
        if ($acme) {
            $lines[] = "# Let's Encrypt HTTP-01 validation and HTTP -> HTTPS redirect";
            $lines[] = "# (WAN tcp/80 is redirected to this port by the firewall)";
            $lines[] = "server {";
            $lines[] = "    listen " . self::ACME_PORT . ";";
            $lines[] = "    server_name _;";
            $lines[] = "    location ^~ /.well-known/acme-challenge/ {";
            $lines[] = "        proxy_pass " . self::UPSTREAM . ";";
            $lines[] = "        proxy_set_header Host \$host;";
            $lines[] = "    }";
            $lines[] = "    location / {";
            $lines[] = "        return 301 https://{$httpsHost}\$request_uri;";
            $lines[] = "    }";
            $lines[] = "}";
            $lines[] = "";
        }
        $lines[] = "server {";
        if ($externalPort === 443) {
            $lines[] = "    listen 443 ssl http2;";
        } else {
            $lines[] = "    listen {$externalPort} ssl http2;";
        }
        $lines[] = "    server_name {$domain};";
        $lines[] = "";
        // A `listen ... ssl` server block with no ssl_certificate pair makes
        // `nginx -t` fail outright, which aborted ztna.apply before nginx was
        // ever reloaded. micrond provisions a self-signed pair at this path when
        // the operator has not installed a certificate of their own.
        $lines[] = "    ssl_certificate     /etc/micron/pki/ztna.crt;";
        $lines[] = "    ssl_certificate_key /etc/micron/pki/ztna.key;";
        $lines[] = "";
        $lines[] = "    # Internal Identity Authentication Subrequest";
        $lines[] = "    location = /api/ztna/verify-auth {";
        $lines[] = "        internal;";
        $lines[] = "        proxy_pass http://127.0.0.1:80/vpn/clientless-gateway/verify-auth;";
        $lines[] = "        proxy_pass_request_body off;";
        $lines[] = "        proxy_set_header Content-Length \"\";";
        $lines[] = "        proxy_set_header X-Original-URI \$request_uri;";
        $lines[] = "        proxy_set_header X-Real-IP \$remote_addr;";
        $lines[] = "    }";
        $lines[] = "";
        // guacd speaks the Guacamole protocol over raw TCP, not WebSocket, so the
        // browser's tunnel goes to micron-guacd-bridge, which verifies the
        // signed session token and relays to the guacd address carried inside
        // that token. The path matches the management UI's Apache vhost.
        $lines[] = "    # HTML5 Guacamole WebSocket Tunnel for In-Browser RDP/SSH/VNC";
        $lines[] = "    # (micron-guacd-bridge -> guacd {$guacdHost}:{$guacdPort})";
        $lines[] = "    location " . self::TUNNEL_PATH . " {";
        $lines[] = "        proxy_pass http://127.0.0.1:" . self::BRIDGE_PORT . ";";
        $lines[] = "        proxy_http_version 1.1;";
        $lines[] = "        proxy_set_header Upgrade \$http_upgrade;";
        $lines[] = "        proxy_set_header Connection \"upgrade\";";
        $lines[] = "        proxy_set_header X-Forwarded-Host \$http_host;";
        $lines[] = "        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;";
        $lines[] = "        proxy_buffering off;";
        $lines[] = "        proxy_read_timeout 3600s;";
        $lines[] = "        proxy_send_timeout 3600s;";
        $lines[] = "    }";
        $lines[] = "";

        // Published Web Applications
        foreach ($resources as $res) {
            if ($res['type'] !== 'web') continue;

            $slug = $res['slug'];
            $host = $res['internal_host'];
            $port = $res['internal_port'];

            $lines[] = "    # Published App: {$res['name']} ({$slug})";
            $lines[] = "    location /apps/{$slug}/ {";
            $lines[] = "        auth_request /api/ztna/verify-auth;";
            $lines[] = "        auth_request_set \$remote_user \$upstream_http_x_remote_user;";
            $lines[] = "        auth_request_set \$remote_email \$upstream_http_x_remote_email;";
            $lines[] = "        auth_request_set \$remote_groups \$upstream_http_x_remote_groups;";
            $lines[] = "        proxy_pass http://{$host}:{$port}/;";
            $lines[] = "        proxy_set_header Host \$host;";
            $lines[] = "        proxy_set_header X-Real-IP \$remote_addr;";
            $lines[] = "        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;";
            $lines[] = "        proxy_set_header X-Remote-User \$remote_user;";
            $lines[] = "        proxy_set_header X-Remote-Email \$remote_email;";
            $lines[] = "        proxy_set_header X-Remote-Groups \$remote_groups;";
            $lines[] = "    }";
            $lines[] = "";
        }

        // Gateway pages (login, portal, launch, viewer) and the static files they
        // use come from the management web server with the URI unchanged. Only
        // these paths are passed through: the appliance's admin pages are not
        // reachable on the gateway hostname.
        $lines[] = "    # Gateway login, portal and in-browser viewer";
        $lines[] = "    location ~ ^/vpn/clientless-gateway/(login|logout|portal|launch/|connect/) {";
        $lines = array_merge($lines, $this->upstreamDirectives());
        $lines[] = "    }";
        $lines[] = "";
        $lines[] = "    # Static assets used by those pages";
        $lines[] = "    location ~ ^/(css|assets|logos|uploads/branding)/ {";
        $lines = array_merge($lines, $this->upstreamDirectives());
        $lines[] = "    }";
        $lines[] = "";
        $lines[] = "    # Everything else lands on the portal";
        $lines[] = "    location / {";
        $lines[] = "        return 302 /vpn/clientless-gateway/portal;";
        $lines[] = "    }";
        $lines[] = "}";

        return [
            'enabled'      => true,
            'nginx_config' => implode("\n", $lines),
            'summary'      => [
                'resources_count' => count($resources),
                'domain'          => $domain,
                'acme'            => $acme,
                'status'          => 'active',
            ],
        ];
    }

    /** proxy_pass to the management web server, telling it the request was HTTPS. */
    private function upstreamDirectives(): array
    {
        return [
            "        proxy_pass " . self::UPSTREAM . ";",
            "        proxy_set_header Host \$http_host;",
            "        proxy_set_header X-Forwarded-Proto https;",
            "        proxy_set_header X-Real-IP \$remote_addr;",
            "        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;",
        ];
    }
}
